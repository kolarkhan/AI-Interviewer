"""Report schemas.

`*LLM` models define the JSON schema the model must follow (Structured Outputs, strict).
They intentionally avoid numeric constraints in the schema; ranges and lengths are enforced
afterwards by `validate_and_normalise`, and the overall score is computed server-side.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict

SCHEMA_VERSION = 1

CATEGORY_KEYS = ("technical_knowledge", "communication_clarity", "answer_relevance", "problem_solving")
CATEGORY_WEIGHTS = {"technical_knowledge": 0.35, "communication_clarity": 0.25,
                    "answer_relevance": 0.20, "problem_solving": 0.20}

DISCLAIMER = (
    "Scores are practice estimates generated by AI from an automatic transcript of this session. "
    "They are not predictions of real hiring outcomes and do not assess personality, honesty or emotions."
)


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class CategoryScoreLLM(_Strict):
    assessed: bool
    score: int
    rationale: str


class ConfidenceIndicatorLLM(_Strict):
    observation: str
    evidence: str
    suggestion: str


class AnswerFeedbackLLM(_Strict):
    question: str
    answer_summary: str
    assessment: Literal["strong", "adequate", "needs_work"]
    feedback: str
    improved_answer: str


class PracticeStepLLM(_Strict):
    title: str
    activity: str
    duration_minutes: int


class BasicReportLLM(_Strict):
    summary: str
    technical_knowledge: CategoryScoreLLM
    communication_clarity: CategoryScoreLLM
    answer_relevance: CategoryScoreLLM
    problem_solving: CategoryScoreLLM
    strengths: list[str]
    improvements: list[str]
    recommended_topics: list[str]


class DetailedReportLLM(BasicReportLLM):
    confidence_indicators: list[ConfidenceIndicatorLLM]
    answer_feedback: list[AnswerFeedbackLLM]
    practice_plan: list[PracticeStepLLM]


class ReportValidationError(ValueError):
    pass


def _clip(text: str, limit: int) -> str:
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _clip_list(items: list[str], max_items: int, limit: int) -> list[str]:
    return [_clip(i, limit) for i in items if i and i.strip()][:max_items]


def validate_and_normalise(raw: BasicReportLLM) -> dict:
    """Validates model output and returns the stored representation. Raises ReportValidationError."""
    categories: dict[str, dict] = {}
    for key in CATEGORY_KEYS:
        cat: CategoryScoreLLM = getattr(raw, key)
        if cat.assessed and not (0 <= cat.score <= 100):
            raise ReportValidationError(f"{key} score out of range: {cat.score}")
        categories[key] = {
            "assessed": cat.assessed,
            "score": int(cat.score) if cat.assessed else None,
            "rationale": _clip(cat.rationale, 600),
        }
    assessed = {k: v for k, v in categories.items() if v["assessed"]}
    if not assessed:
        raise ReportValidationError("no category was assessed")
    weight_sum = sum(CATEGORY_WEIGHTS[k] for k in assessed)
    overall = round(sum(v["score"] * CATEGORY_WEIGHTS[k] for k, v in assessed.items()) / weight_sum)

    if not raw.summary.strip():
        raise ReportValidationError("empty summary")
    out: dict = {
        "overall_score": int(overall),
        "categories": categories,
        "summary": _clip(raw.summary, 1200),
        "strengths": _clip_list(raw.strengths, 6, 300),
        "improvements": _clip_list(raw.improvements, 6, 300),
        "recommended_topics": _clip_list(raw.recommended_topics, 8, 120),
        "confidence_indicators": [],
        "answer_feedback": [],
        "practice_plan": [],
    }
    if isinstance(raw, DetailedReportLLM):
        out["confidence_indicators"] = [
            {"observation": _clip(c.observation, 300), "evidence": _clip(c.evidence, 300),
             "suggestion": _clip(c.suggestion, 300)}
            for c in raw.confidence_indicators[:5]
        ]
        out["answer_feedback"] = [
            {"question": _clip(a.question, 400), "answer_summary": _clip(a.answer_summary, 600),
             "assessment": a.assessment, "feedback": _clip(a.feedback, 800),
             "improved_answer": _clip(a.improved_answer, 1500)}
            for a in raw.answer_feedback[:12]
        ]
        out["practice_plan"] = [
            {"title": _clip(p.title, 120), "activity": _clip(p.activity, 500),
             "duration_minutes": max(5, min(240, int(p.duration_minutes)))}
            for p in raw.practice_plan[:7]
        ]
    return out
